/** Общая адаптация пояснений под законодательство ПМР */
function adaptPmr(text) {
  if (!text) return 'Согласно ПДД ПМР (Постановление Правительства ПМР № 126 от 02.06.2017).';
  let t = text
    .replace(/КоАП РФ/gi, 'КоАП ПМР')
    .replace(/Кодекс РФ об административных правонарушениях/gi, 'Кодекс ПМР об административных правонарушениях')
    .replace(/Уголовный [KК]одекс РФ/gi, 'Уголовный кодекс ПМР')
    .replace(/УК РФ/gi, 'УК ПМР')
    .replace(/гражданского кодекса РФ/gi, 'Гражданского кодекса ПМР')
    .replace(/Гражданский кодекс РФ/gi, 'Гражданский кодекс ПМР')
    .replace(/ФЗ «Об обязательном страховании[^»]*»/gi, 'законодательство ПМР об обязательном страховании')
    .replace(/«ОСАГО»|ОСАГО/gi, 'обязательное страхование гражданской ответственности')
    .replace(/инспектор(ов|а)?\s+ГИБДД/gi, 'сотрудников ГАИ ПМР')
    .replace(/ГИБДД/g, 'ГАИ ПМР')
    .replace(/Почта России/g, 'почтовая служба')
    .replace(/ПДД РФ/g, 'ПДД ПМР')
    .replace(/\(«Дорожные знаки»\)/g, '(ПДД ПМР, дорожные знаки)')
    .replace(/\(«Дорожные знаки»,/g, '(ПДД ПМР, дорожные знаки,')
    .replace(/\(Пункт/g, '(ПДД ПМР, пункт')
    .replace(/\s{2,}/g, ' ')
    .trim();
  if (!/ПДД ПМР|КоАП ПМР|УК ПМР/i.test(t)) {
    t += ' (ПДД ПМР, Постановление № 126 от 02.06.2017).';
  }
  return t;
}

module.exports = { adaptPmr };
